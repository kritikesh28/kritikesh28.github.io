/** t('search.matchesN', { n: 3, q: 'stars' }) */
export const useT =
  (lang: Lang) =>
  (key: UiKey, vars: Record<string, string | number> = {}) => {
    const s = ui[lang]?.[key] ?? ui[DEFAULT_LANG][key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
  };
